import json
import threading

from checkout_api import cli as api_cli
from checkout_api.app import CheckoutApp, build_server
from slokit import cli


def run(capsys, *argv):
    code = cli.main(list(argv))
    return code, capsys.readouterr()


def test_budget_json(capsys):
    code, out = run(
        capsys,
        "budget",
        "--objective",
        "99.9",
        "--window",
        "30d",
        "--requests",
        "10000000",
        "--json",
    )
    data = json.loads(out.out)
    assert code == 0
    assert data["allowed_downtime"] == "43m12s"
    assert data["allowed_failed_requests"] == 10000
    assert [t["burn_rate"] for t in data["burn_rate_alerts"]] == [14.4, 6.0, 3.0, 1.0]
    assert data["burn_rate_alerts"][0]["error_ratio_threshold"] == 0.0144
    assert data["burn_rate_alerts"][0]["exhausts_full_budget_in"] == "2d2h"


def test_budget_accepts_ratio_and_text_output(capsys):
    code, out = run(capsys, "budget", "--objective", "0.99")
    assert code == 0 and "allowed_downtime: 7h12m" in out.out


def test_status_exit_code_reflects_slo(capsys):
    code, out = run(
        capsys, "status", "--objective", "99.9", "--good", "999500", "--total", "1000000", "--json"
    )
    assert code == 0 and json.loads(out.out)["budget_remaining_pct"] == 50.0
    code, _ = run(capsys, "status", "--objective", "99.9", "--good", "990000", "--total", "1000000")
    assert code == 1


def test_burn(capsys):
    code, out = run(capsys, "burn", "--objective", "99.9", "--error-ratio", "0.0144", "--json")
    data = json.loads(out.out)
    assert data["burn_rate"] == 14.4 and data["budget_consumed_in_1h_pct"] == 2.0


def test_invalid_input_exit_2(capsys):
    code, out = run(capsys, "budget", "--objective", "100")
    assert code == 2 and "error:" in out.err


def test_validate_and_generate_check(capsys, root, tmp_path):
    spec = str(root / "slos" / "checkout-api.yaml")
    code, out = run(capsys, "validate", spec)
    assert code == 0 and "2 SLOs" in out.out
    target = tmp_path / "rules.yml"
    code, _ = run(capsys, "generate", spec, "--out", str(target), "--check")
    assert code == 1  # missing file counts as drift
    code, _ = run(capsys, "generate", spec, "--out", str(target))
    assert code == 0 and target.read_text().startswith("# Generated by slokit")
    code, _ = run(capsys, "generate", spec, "--out", str(target), "--check")
    assert code == 0


def test_loadgen_against_local_server(capsys):
    server = build_server(CheckoutApp(), "127.0.0.1", 0)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        code = api_cli.main(
            [
                "loadgen",
                "--target",
                f"http://127.0.0.1:{server.server_address[1]}",
                "--requests",
                "25",
                "--rate",
                "0",
                "--seed",
                "3",
            ]
        )
        result = json.loads(capsys.readouterr().out)
        assert code == 0 and result["sent"] == 25
        assert set(result["status_codes"]) <= {"200", "201"}
    finally:
        server.shutdown()
        server.server_close()


def test_loadgen_rejects_non_http_target(capsys):
    assert api_cli.main(["loadgen", "--target", "file:///etc/passwd", "--requests", "1"]) == 2


def test_percent_objective_is_normalised(capsys):
    _, out = run(capsys, "budget", "--objective", "99.9", "--json")
    assert json.loads(out.out)["objective"] == 0.999
