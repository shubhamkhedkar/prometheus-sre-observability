import yaml

from slokit import model, rules


def generated(root):
    spec = model.load(root / "slos" / "checkout-api.yaml")
    return spec, rules.rule_file(spec)


def test_required_windows_sorted(root):
    spec, _ = generated(root)
    assert rules.required_windows(spec) == ["5m", "30m", "1h", "2h", "6h", "1d", "3d", "30d"]


def test_recording_rules_per_slo(root):
    spec, doc = generated(root)
    rec = doc["groups"][0]["rules"]
    # 8 windows + objective + budget + remaining, per SLO
    assert len(rec) == 11 * len(spec.slos)
    names = {(r["record"], r["labels"]["slo"]) for r in rec}
    assert ("slo:sli_error:ratio_rate3d", "latency") in names
    assert ("slo:error_budget_remaining:ratio", "availability") in names
    for r in rec:
        assert r["labels"]["service"] == "checkout-api"


def test_alert_thresholds_match_workbook(root):
    _, doc = generated(root)
    alerts = doc["groups"][1]["rules"]
    avail = [a for a in alerts if a["labels"]["slo"] == "availability"]
    assert [(a["labels"]["burn_rate"], a["labels"]["severity"]) for a in avail] == [
        ("14.4", "page"),
        ("6", "page"),
        ("3", "ticket"),
        ("1", "ticket"),
    ]
    fast = avail[0]["expr"]
    assert (
        'slo:sli_error:ratio_rate1h{service="checkout-api",slo="availability"} > (14.4 * 0.001)'
        in fast
    )
    assert "\nand\n" in fast and "ratio_rate5m" in fast
    latency_fast = next(a for a in alerts if a["labels"]["slo"] == "latency")
    assert "(14.4 * 0.01)" in latency_fast["expr"]


def test_every_alert_has_runbook_and_unique_labels(root):
    _, doc = generated(root)
    alerts = doc["groups"][1]["rules"]
    keys = {tuple(sorted(a["labels"].items())) for a in alerts}
    assert len(keys) == len(alerts)  # promtool rejects duplicate rule label sets
    for a in alerts:
        assert a["annotations"]["runbook_url"].endswith("#errorbudgetburn")
        assert a["annotations"]["summary"]


def test_render_is_valid_yaml_with_header(root):
    spec, doc = generated(root)
    text = rules.render(spec, "slos/checkout-api.yaml")
    assert text.startswith("# Generated by slokit")
    assert yaml.safe_load(text) == doc


def test_committed_rules_are_up_to_date(root):
    spec, _ = generated(root)
    committed = (root / "prometheus" / "rules" / "slo-checkout-api.yml").read_text()
    assert committed == rules.render(spec, "slos/checkout-api.yaml"), "run `make slo-rules`"


def test_custom_window_scales_burn_rate():
    spec = model.parse(
        {
            "service": "svc",
            "window": "28d",
            "slos": [
                {
                    "name": "avail",
                    "objective": 99.5,
                    "sli": {"errors": "e[$window]", "total": "t[$window]"},
                }
            ],
        }
    )
    burns = [a["labels"]["burn_rate"] for a in rules.alert_rules(spec)]
    assert burns == ["13.44", "5.6", "2.8", "0.933333"]
