"""Generate Prometheus recording and alerting rules for SLOs.

Output layout per service:
  group slo:<service>:recording  - error ratio for every window an alert tier needs plus the
                                   SLO window, objective, error budget and remaining budget
  group slo:<service>:alerts     - one ErrorBudgetBurn alert per (SLO, tier); a tier fires only
                                   when BOTH its long and short window exceed the burn threshold
"""

from __future__ import annotations

from typing import Any

import yaml

from . import durations
from .budget import burn_rate_for_consumption
from .model import SLO, ServiceSLOs

HEADER = (
    "# Generated by slokit from {source}. Do not edit by hand;\n"
    "# change the spec and run `make slo-rules` (CI-style check: `make slo-check`).\n"
)


def ratio_metric(window: str) -> str:
    return f"slo:sli_error:ratio_rate{window}"


def required_windows(spec: ServiceSLOs) -> list[str]:
    windows = {spec.window}
    for tier in spec.tiers:
        windows.update((tier.long_window, tier.short_window))
    return sorted(windows, key=durations.parse)


def _num(value: float) -> str:
    return f"{value:.6g}"


def _selector(spec: ServiceSLOs, slo: SLO) -> str:
    return f'{{service="{spec.service}",slo="{slo.name}"}}'


def recording_rules(spec: ServiceSLOs) -> list[dict[str, Any]]:
    rules: list[dict[str, Any]] = []
    for slo in spec.slos:
        labels = {"service": spec.service, "slo": slo.name}
        for window in required_windows(spec):
            rules.append(
                {
                    "record": ratio_metric(window),
                    "expr": f"(\n  {slo.errors(window)}\n)\n/\n(\n  {slo.total(window)}\n)\n",
                    "labels": dict(labels),
                }
            )
        rules.append(
            {
                "record": "slo:objective:ratio",
                "expr": f"vector({_num(slo.objective)})",
                "labels": dict(labels),
            }
        )
        rules.append(
            {
                "record": "slo:error_budget:ratio",
                "expr": f"vector({_num(slo.budget)})",
                "labels": dict(labels),
            }
        )
        rules.append(
            {
                "record": "slo:error_budget_remaining:ratio",
                "expr": (
                    f"1 - ({ratio_metric(spec.window)}{_selector(spec, slo)} / {_num(slo.budget)})"
                ),
                "labels": dict(labels),
            }
        )
    return rules


def alert_rules(spec: ServiceSLOs) -> list[dict[str, Any]]:
    rules: list[dict[str, Any]] = []
    slo_seconds = spec.window_seconds
    for slo in spec.slos:
        sel = _selector(spec, slo)
        for tier in spec.tiers:
            burn = burn_rate_for_consumption(
                tier.budget_consumed, durations.parse(tier.long_window), slo_seconds
            )
            threshold = f"({_num(burn)} * {_num(slo.budget)})"
            expr = (
                f"{ratio_metric(tier.long_window)}{sel} > {threshold}\n"
                f"and\n"
                f"{ratio_metric(tier.short_window)}{sel} > {threshold}\n"
            )
            pct = _num(tier.budget_consumed * 100)
            rule: dict[str, Any] = {
                "alert": "ErrorBudgetBurn",
                "expr": expr,
            }
            if tier.for_ != "0s":
                rule["for"] = tier.for_
            rule["labels"] = {
                "service": spec.service,
                "slo": slo.name,
                "severity": tier.severity,
                "long_window": tier.long_window,
                "short_window": tier.short_window,
                "burn_rate": _num(burn),
            }
            rule["annotations"] = {
                "summary": (
                    f"{spec.service} {slo.name} SLO is burning error budget "
                    f"at more than {_num(burn)}x"
                ),
                "description": (
                    f"Error ratio over {tier.long_window} and {tier.short_window} is above "
                    f"{_num(burn * slo.budget * 100)}% (objective {_num(slo.objective * 100)}% "
                    f"over {spec.window}). At this rate {pct}% of the budget is spent "
                    f"in {tier.long_window}."
                ),
            }
            if spec.runbook_base:
                rule["annotations"]["runbook_url"] = f"{spec.runbook_base}#errorbudgetburn"
            rules.append(rule)
    return rules


def rule_file(spec: ServiceSLOs) -> dict[str, Any]:
    return {
        "groups": [
            {"name": f"slo:{spec.service}:recording", "rules": recording_rules(spec)},
            {"name": f"slo:{spec.service}:alerts", "rules": alert_rules(spec)},
        ]
    }


class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_Dumper.add_representer(str, _str_presenter)


def render(spec: ServiceSLOs, source: str) -> str:
    body = yaml.dump(
        rule_file(spec), Dumper=_Dumper, sort_keys=False, width=200, default_flow_style=False
    )
    return HEADER.format(source=source) + body
